// Downloads Unbounded and Onest (free, SIL Open Font License) into public/fonts and writes src/app/fonts.css.
// Run once: node scripts/fetch-fonts.mjs   (the results are committed, so nobody needs the internet to run the app)
import { mkdirSync, writeFileSync } from 'node:fs';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const FAMILIES = [
  { name: 'Unbounded', slug: 'unbounded', query: 'Unbounded:wght@200..900' },
  { name: 'Onest', slug: 'onest', query: 'Onest:wght@100..900' },
];
// Latin for English, Cyrillic for Russian, and the extended Cyrillic that holds the Tajik letters ғ ӣ қ ӯ ҳ ҷ.
const WANTED = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'];

async function get(url, binary = false) {
  for (let attempt = 1; attempt <= 5; attempt++) {
    try {
      const response = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(60_000) });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return binary ? Buffer.from(await response.arrayBuffer()) : await response.text();
    } catch (error) {
      console.log(`  retry ${attempt} for ${url}: ${error.message}`);
    }
  }
  throw new Error(`Could not download ${url}`);
}

mkdirSync('public/fonts', { recursive: true });
let css = '/* Generated by scripts/fetch-fonts.mjs. Unbounded and Onest are free (SIL Open Font License). */\n';

for (const family of FAMILIES) {
  const source = await get(`https://fonts.googleapis.com/css2?family=${family.query}&display=swap`);
  const blocks = [...source.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
  for (const [, subset, body] of blocks) {
    if (!WANTED.includes(subset)) continue;
    const url = /url\((https:[^)]+)\)/.exec(body)?.[1];
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
    if (!url || !weight || !range) throw new Error(`Unexpected CSS for ${family.name} ${subset}`);
    const file = `${family.slug}-${subset}.woff2`;
    writeFileSync(`public/fonts/${file}`, await get(url, true));
    console.log(`saved ${file}`);
    css += `\n@font-face {\n  font-family: '${family.name}';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('/fonts/${file}') format('woff2');\n  unicode-range: ${range};\n}\n`;
  }
}
writeFileSync('src/app/fonts.css', css);
console.log('fonts.css written');
